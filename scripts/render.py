"""Validate storyboard.json, then render a storyboard sheet, a preview or the final reel + cover.

Usage: python3 render.py storyboard|preview|final EDIT_DIR [--name my-reel]
  storyboard -> EDIT_DIR/storyboard.png (one still per moment) and a printed timeline
  preview    -> EDIT_DIR/preview.mp4 (half resolution, fast)
  final      -> EDIT_DIR/final.mp4 + cover.png, copied to <Studio>/Exports/<name>/
Strings starting with "studio:" in the storyboard are files in the Studio folder.
Instagram finishing on final: loudness normalised to -14 LUFS / -1.5 dBTP (two-pass), 320 kbps audio;
with "music": {"labelSong": true} it also exports an upload copy without the music (add the song in
Instagram's audio picker so it stays licensed) next to a preview copy with it.
Self-test: python3 render.py --selftest
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from rf_config import load, run  # noqa: E402


def registry(engine: Path):
    fx = set(re.findall(r"^\s{2}(\w+)[,:]", (engine / "src/effects/index.ts").read_text(encoding="utf-8"), re.M))
    looks = set(re.findall(r"^\s{2}\"?([\w-]+)\"?: \{", (engine / "src/theme.ts").read_text(encoding="utf-8"), re.M))
    caps = set(re.findall(r"^\s{2}\"?([\w-]+)\"?: \{", (engine / "src/captionStyles.ts").read_text(encoding="utf-8"), re.M))
    return fx, looks, caps


def sync_custom(studio: Path, engine: Path) -> set:
    dst = engine / "src/custom"
    dst.mkdir(exist_ok=True)
    for old in dst.glob("*.tsx"):
        old.unlink()
    names = []
    for f in sorted((studio / "custom-effects").glob("*.tsx")):
        if not re.fullmatch(r"[A-Z]\w*", f.stem):
            sys.exit(f"custom effect file name must be PascalCase: {f.name}")
        shutil.copy2(f, dst / f.name)
        names.append(f.stem)
    (dst / "index.ts").write_text(
        "// generated by render.py from <Studio>/custom-effects\nimport type {FX} from \"../kit\";\n"
        + "".join(f"import {{{n}}} from \"./{n}\";\n" for n in names)
        + "export const custom: Record<string, FX> = {" + ", ".join(names) + "};\n", encoding="utf-8")
    return set(names)


def link(src: Path, dst: Path):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def collect_assets(node, studio: Path, pub: Path, missing: list):
    if isinstance(node, dict):
        return {k: collect_assets(v, studio, pub, missing) for k, v in node.items()}
    if isinstance(node, list):
        return [collect_assets(v, studio, pub, missing) for v in node]
    if isinstance(node, str) and node.startswith("studio:"):
        rel = node[len("studio:"):].lstrip("/")
        src = studio / rel
        if not src.exists():
            missing.append(str(src))
            return node
        link(src, pub / "studio" / rel)
        return f"studio/{rel}"
    return node


def face_at(faces, t):
    return min(faces, key=lambda f: abs(f["t"] - t)) if faces else None


# Instagram Reels UI covers these parts of a 9:16 frame (fractions of height/width)
SAFE_TOP, SAFE_BOTTOM, SAFE_RIGHT = 0.08, 0.79, 0.86


def snap_to_beats(story, beats, tol=0.12) -> int:
    """Move moment/zoom/transition starts within tol seconds of a beat onto the beat (keeps durations)."""
    if not beats:
        return 0
    near = lambda t: min(beats, key=lambda b: abs(b - t))  # noqa: E731
    n = 0
    for item, key in [(m, "start") for m in story.get("moments", [])] + [(z, "start") for z in story.get("zooms", [])] \
            + [(tr, "time") for tr in story.get("transitions", [])]:
        b = near(item[key])
        d = round(b - item[key], 3)
        if 0 < abs(d) <= tol and (key == "time" or item["end"] + d <= story["duration"]):
            item[key] = round(b, 3)
            if "end" in item:
                item["end"] = round(item["end"] + d, 3)
            n += 1
    return n


def safe_zone_warnings(story) -> list:
    w = []
    cap = story.get("captions") or {}
    if cap and not (SAFE_TOP < cap.get("position", 0.72) < SAFE_BOTTOM - 0.03):
        w.append(f"captions at {cap.get('position')} sit under Instagram's UI; keep 0.1-0.76")
    for m in story.get("moments", []):
        y, x = (m.get("props") or {}).get("y"), (m.get("props") or {}).get("x")
        if isinstance(y, (int, float)) and not (SAFE_TOP <= y <= SAFE_BOTTOM):
            w.append(f"moment {m.get('id', m['effect'])}: y={y} is under Instagram's UI (keep {SAFE_TOP}-{SAFE_BOTTOM})")
        if isinstance(x, (int, float)) and x > SAFE_RIGHT and isinstance(y, (int, float)) and y > 0.5:
            w.append(f"moment {m.get('id', m['effect'])}: x={x} collides with the like/comment buttons")
    return w


def loudnorm(src: Path, dst: Path, target=-14.0, tp=-1.5):
    """Two-pass EBU R128 loudness normalisation; video stream copied untouched."""
    r = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(src), "-af", f"loudnorm=I={target}:TP={tp}:LRA=11:print_format=json",
                        "-f", "null", "-"], capture_output=True, text=True)
    m = json.loads(r.stderr[r.stderr.rindex("{"):r.stderr.rindex("}") + 1])
    af = (f"loudnorm=I={target}:TP={tp}:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:"
          f"measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true")
    run(["ffmpeg", "-y", "-v", "error", "-i", src, "-c:v", "copy", "-af", af, "-ar", "48000", "-c:a", "aac", "-b:a", "320k",
         "-movflags", "+faststart", dst])
    return float(m["input_i"])


def selftest():
    st = {"duration": 10, "moments": [{"start": 1.05, "end": 2}, {"start": 3.3, "end": 4}], "zooms": [{"start": 4.9, "end": 6}],
          "transitions": [{"time": 7.02}]}
    n = snap_to_beats(st, [1.0, 1.5, 3.0, 5.0, 7.0])
    assert n == 3 and st["moments"][0] == {"start": 1.0, "end": 1.95} and st["moments"][1]["start"] == 3.3, st
    assert st["zooms"][0] == {"start": 5.0, "end": 6.1} and st["transitions"][0]["time"] == 7.0, st
    assert safe_zone_warnings({"captions": {"position": 0.9}, "moments": [{"effect": "X", "props": {"y": 0.95}}]}).__len__() == 2
    print("render.py selftest ok")


def check(story, fx, looks, caps):
    errs = []
    dur = story["duration"]
    if story.get("look", "clean") not in looks:
        errs.append(f"unknown look {story.get('look')!r}; have {sorted(looks)}")
    cs = story.get("captions", {}).get("style", "pop")
    if story.get("captions") is not None and cs not in caps:
        errs.append(f"unknown caption style {cs!r}; have {sorted(caps)}")
    for i, m in enumerate(story.get("moments", [])):
        tag = f"moment {m.get('id', i)}"
        if m.get("effect") not in fx:
            errs.append(f"{tag}: unknown effect {m.get('effect')!r}")
        if not (0 <= m["start"] < m["end"] <= dur + 0.01):
            errs.append(f"{tag}: bad time {m['start']}-{m['end']} (reel is {dur:.2f}s)")
        if m.get("layer") == "behind" and not story.get("foreground"):
            errs.append(f"{tag}: layer 'behind' needs the person cut-out; run vision.py matte")
    for z in story.get("zooms", []):
        if not (0 <= z["start"] < z["end"] <= dur + 0.01):
            errs.append(f"zoom {z}: bad time")
    if errs:
        sys.exit("storyboard problems:\n- " + "\n- ".join(errs))


def main():
    if "--selftest" in sys.argv:
        return selftest()
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["storyboard", "preview", "final"])
    ap.add_argument("edit_dir")
    ap.add_argument("--name")
    a = ap.parse_args()
    cfg = load()
    ed = Path(a.edit_dir).expanduser().resolve()
    studio, engine = Path(cfg["studio"]), Path(cfg["engine"])
    story = json.loads((ed / "storyboard.json").read_text(encoding="utf-8"))

    pub = ed / "public"
    shutil.rmtree(pub, ignore_errors=True)
    pub.mkdir()
    for key in ("video", "foreground"):
        if story.get(key):
            link(ed / story[key], pub / story[key])
    if story.get("captions", {}) in (None, False):  # "captions": null turns them off
        story["captions"] = None
    else:
        cap = story.setdefault("captions", {})
        if "words" not in cap:
            cap["words"] = json.loads((ed / cap.get("wordsFile", "words_cut.json")).read_text(encoding="utf-8"))["words"]
    if (ed / "faces.json").exists() and "faces" not in story:
        story["faces"] = json.loads((ed / "faces.json").read_text(encoding="utf-8"))["faces"]
    brand_file = studio / "brand" / "brand.json"
    brand = json.loads(brand_file.read_text(encoding="utf-8")) if brand_file.exists() else {}
    story["palette"] = {**brand.get("palette", {}), **story.get("palette", {})}
    story.setdefault("look", brand.get("look", "clean"))
    edl = json.loads((ed / "edl.json").read_text(encoding="utf-8")) if (ed / "edl.json").exists() else {}
    if edl.get("gradeFilter") and "grade" not in story["palette"]:
        story["palette"]["grade"] = "none"  # footage already graded by FFmpeg in cut.py
    if story.get("beatSync") and (ed / "beats.json").exists():
        tol = story["beatSync"].get("tolerance", 0.12) if isinstance(story["beatSync"], dict) else 0.12
        story["beats"] = json.loads((ed / "beats.json").read_text(encoding="utf-8"))["beats"]
        print(f"beat sync: snapped {snap_to_beats(story, story['beats'], tol)} starts onto beats")
    for w in safe_zone_warnings(story):
        print(f"safe zone: {w}")

    missing = []
    story = collect_assets(story, studio, pub, missing)
    if missing:
        sys.exit("missing Studio files:\n- " + "\n- ".join(missing))
    fx, looks, caps = registry(engine)
    fx |= sync_custom(studio, engine)
    check(story, fx, looks, caps)

    # cover: best face frame unless a time is given; title goes on the side away from the face
    cover = story.setdefault("cover", {})
    faces = story.get("faces", [])
    if "time" not in cover:
        cover["time"] = max(faces, key=lambda f: f.get("q", 0))["t"] if faces else story["duration"] * 0.3
    f = face_at(faces, cover["time"])
    cover["face"] = f
    run(["ffmpeg", "-y", "-v", "error", "-ss", f"{cover['time']:.3f}", "-i", ed / story["video"], "-frames:v", "1",
         "-q:v", "2", pub / "cover_frame.jpg"])
    cover["frame"] = "cover_frame.jpg"

    props = ed / ".props.json"
    props.write_text(json.dumps(story, ensure_ascii=False), encoding="utf-8")
    bundle = ed / ".bundle"
    npx = ["npx", "--no-install", "remotion"]
    run(npx + ["bundle", "src/index.ts", "--public-dir", pub, "--out-dir", bundle], cwd=engine)

    fps = story.get("fps", 30)
    if a.mode == "storyboard":
        sbprops = ed / ".props-storyboard.json"
        sbprops.write_text(json.dumps({**story, "safeZones": True}, ensure_ascii=False), encoding="utf-8")
        sb = ed / "storyboard"
        shutil.rmtree(sb, ignore_errors=True)
        sb.mkdir()
        moments = sorted(story.get("moments", []), key=lambda m: m["start"])
        for i, m in enumerate(moments):
            frame = int(((m["start"] + m["end"]) / 2) * fps)
            run(npx + ["still", bundle, "Reel", sb / f"{i:03d}.png", f"--props={sbprops}", f"--frame={frame}", "--scale=0.3"], cwd=engine)
            print(f"{i + 1:>2}. {m['start']:6.2f}-{m['end']:6.2f}s  {m['effect']:<16} {m.get('layer', 'front'):<6} "
                  f"{json.dumps(m.get('props', {}), ensure_ascii=False)[:90]}")
        if moments:
            cols = min(4, len(moments))
            run(["ffmpeg", "-y", "-v", "error", "-i", sb / "%03d.png", "-vf",
                 f"tile={cols}x{-(-len(moments) // cols)}:padding=8:color=white", "-frames:v", "1", ed / "storyboard.png"])
            print(f"storyboard sheet: {ed / 'storyboard.png'}")
        return

    if a.mode == "preview":
        run(npx + ["render", bundle, "Reel", ed / "preview.mp4", f"--props={props}", "--codec=h264", "--scale=0.5", "--crf=26"], cwd=engine)
        print(f"rendered {ed / 'preview.mp4'}")
        return

    def final(props_file: Path, out: Path):
        raw = ed / f".{out.stem}-raw.mp4"
        run(npx + ["render", bundle, "Reel", raw, f"--props={props_file}", "--codec=h264", "--crf=16", "--audio-bitrate=320k"], cwd=engine)
        before = loudnorm(raw, out)
        raw.unlink()
        print(f"rendered {out} (loudness {before:.1f} -> -14 LUFS)")

    final(props, ed / "final.mp4")
    label = bool((story.get("music") or {}).get("labelSong"))
    if label:
        nomusic = ed / ".props-upload.json"
        nomusic.write_text(json.dumps({**story, "music": None}, ensure_ascii=False), encoding="utf-8")
        final(nomusic, ed / "upload.mp4")
    run(npx + ["still", bundle, "Cover", ed / "cover.png", f"--props={props}"], cwd=engine)
    name = a.name or ed.name.removesuffix("-reel")
    exp = studio / "Exports" / name
    exp.mkdir(parents=True, exist_ok=True)
    outs = {"final.mp4": f"{name}-preview.mp4" if label else f"{name}.mp4", "upload.mp4": f"{name}-upload.mp4",
            "cover.png": "cover.png", "caption.txt": "caption.txt"}
    for fn, dst in outs.items():
        if (ed / fn).exists() and (fn != "upload.mp4" or label):
            shutil.copy2(ed / fn, exp / dst)
    print(f"exported to {exp}" + ("  (upload = no music: pick the song in Instagram's audio picker)" if label else ""))


if __name__ == "__main__":
    main()
